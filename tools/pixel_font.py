ROWS = 9


def masks(rows):
    parts = rows.split()
    assert 7 <= len(parts) <= ROWS, rows
    out = []
    for r in parts + ["....."] * (ROWS - len(parts)):
        assert len(r) == 5 and set(r) <= {'.', '#'}, r
        m = 0
        for i, ch in enumerate(r):
            if ch == '#':
                m |= 1 << (4 - i)
        out.append(m)
    return out


def table():
    return sorted((ord(ch), masks(rows)) for ch, rows in G.items())


def swift_source():
    lines = [
        "// Made by tools/pixel_font.py. Don't edit by hand: change the script and run it again.",
        "",
        "extension PixelFont {",
        "    /// Unicode scalar -> 9 rows, each a 5-bit mask (bit 4 is the left column).",
        "    static let glyphs: [UInt32: [UInt8]] = [",
    ]
    for code, m in table():
        lines.append(f"        {code}: [{', '.join(str(v) for v in m)}],")
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def js_source():
    lines = [
        "'use strict';",
        "// Made by tools/pixel_font.py. Don't edit by hand: change the script and run it again.",
        "// Unicode code point -> 9 rows, each a 5-bit mask (bit 4 is the left column).",
        "",
        "const GLYPHS = {",
    ]
    for code, m in table():
        lines.append(f"  {code}: [{', '.join(str(v) for v in m)}],")
    lines += ["};", "", "module.exports = { GLYPHS };", ""]
    return "\n".join(lines)


